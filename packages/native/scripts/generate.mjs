import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { editorOutputs, engineFiles } from "./generate-editors.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const catalog = JSON.parse(await readFile(resolve(here, "../src/catalog.json"), "utf8"));

const HEADER = "// Generated by packages/native/scripts/generate.mjs from src/catalog.json. Do not edit: change the catalog and run `pnpm --filter @pli.dev/native generate`.\n";

const camel = (s) => s[0].toLowerCase() + s.slice(1);
const optional = (t) => t.endsWith("?");
const base = (t) => t.replace("?", "");

/** The values of each enum used by the catalog, by name. */
const enums = new Map();
for (const c of catalog.commands) for (const p of c.params) if (p.enum) enums.set(p.enum, p.oneOf);

// ---- Swift ----

const ENUM_DOCS = { Alignment: "alignment", StyleKind: "a style's kind", ListMarker: "how a list is marked" };
const kebabToCamel = (v) => v.replace(/-(\w)/g, (_, c) => c.toUpperCase());

const swiftType = (p) => {
  const t = p.enum ? `Pli${p.enum}` : { string: "String", int: "Int", double: "Double", bool: "Bool" }[base(p.type)];
  return optional(p.type) ? `${t}?` : t;
};
const swiftReturn = (r) => ({ bool: "Bool", void: "Void", "string?": "String?" })[r];
const swiftValue = (p) => (p.enum ? `${p.name}${optional(p.type) ? "?" : ""}.rawValue` : p.name);

function swift() {
  let out = HEADER + "import Foundation\n\n";
  for (const [name, values] of enums) {
    out += `/// The choices for ${ENUM_DOCS[name] ?? name}.\npublic enum Pli${name}: String, Codable, CaseIterable, Sendable {\n`;
    for (const v of values) out += kebabToCamel(v) === v ? `    case ${v}\n` : `    case ${kebabToCamel(v)} = "${v}"\n`;
    out += "}\n\n";
  }
  out += "extension PliDocument {\n";
  for (const c of catalog.commands) {
    const single = c.params.length === 1;
    const params = c.params.map((p) => `${single ? "_ " : ""}${p.name}: ${swiftType(p)}${!single && optional(p.type) ? " = nil" : ""}`).join(", ");
    const args = c.params.map(swiftValue).map((v, i) => (c.params[i].enum ? v : v)).join(", ");
    const argList = c.params.length === 0 ? "[]" : `[${c.params.map((p) => (p.enum ? (optional(p.type) ? `${p.name}?.rawValue as Any?` : `${p.name}.rawValue as Any?`) : `${p.name} as Any?`)).join(", ")}]`;
    const ret = swiftReturn(c.returns);
    out += `    /// ${c.doc}\n`;
    if (c.returns === "void") {
      out += `    public func ${c.name}(${params}) throws {\n        try invokeVoid("${c.name}", ${argList})\n    }\n\n`;
    } else {
      out += `    @discardableResult\n    public func ${c.name}(${params}) throws -> ${ret} {\n        try invoke("${c.name}", ${argList})\n    }\n\n`;
    }
    void args;
  }
  out += "}\n";
  return out;
}

// ---- Kotlin ----

const kotlinType = (p) => {
  const t = p.enum ? `Pli${p.enum}` : { string: "String", int: "Int", double: "Double", bool: "Boolean" }[base(p.type)];
  return optional(p.type) ? `${t}?` : t;
};
const kotlinReturn = (r) => ({ bool: "Boolean", void: "Unit", "string?": "String?" })[r];

function kotlin() {
  let out = HEADER + "package dev.pli\n\n";
  for (const [name, values] of enums) {
    out += `/** The choices for ${ENUM_DOCS[name] ?? name}. */\nenum class Pli${name}(val wire: String) {\n${values.map((v, i) => `    ${v.toUpperCase().replace(/-/g, "_")}("${v}")${i === values.length - 1 ? ";" : ","}`).join("\n")}\n}\n\n`;
  }
  out += "/** Everything that can be done to a document, as methods. */\ninterface PliCommands {\n    fun <T> invoke(name: String, vararg args: Any?, read: (kotlinx.serialization.json.JsonElement?) -> T): T\n\n";
  for (const c of catalog.commands) {
    const params = c.params.map((p) => `${p.name}: ${kotlinType(p)}${optional(p.type) ? " = null" : ""}`).join(", ");
    const args = c.params.map((p) => (p.enum ? (optional(p.type) ? `${p.name}?.wire` : `${p.name}.wire`) : p.name)).join(", ");
    const ret = kotlinReturn(c.returns);
    const read = c.returns === "bool" ? "{ it?.jsonPrimitive?.booleanOrNull ?: false }" : c.returns === "void" ? "{ }" : "{ it?.takeIf { v -> v !is kotlinx.serialization.json.JsonNull }?.jsonPrimitive?.contentOrNull }";
    out += `    /** ${c.doc} */\n    fun ${c.name}(${params}): ${ret} = invoke("${c.name}"${args ? `, ${args}` : ""}, read = ${read})\n\n`;
  }
  out += "}\n";
  return out.replace("package dev.pli\n", "package dev.pli\n\nimport kotlinx.serialization.json.booleanOrNull\nimport kotlinx.serialization.json.contentOrNull\nimport kotlinx.serialization.json.jsonPrimitive\n");
}

export const outputs = {
  swift: { path: resolve(root, "packages/swift/Sources/Pli/Commands.generated.swift"), text: swift() },
  kotlin: { path: resolve(root, "packages/kotlin/src/main/kotlin/dev/pli/Commands.generated.kt"), text: kotlin() },
  ...editorOutputs,
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const { path, text } of Object.values(outputs)) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, text);
    console.log(path);
  }
  // The engines themselves, beside each wrapper.
  for (const file of engineFiles) {
    for (const target of [`packages/swift/Sources/Pli/Resources/${file}`, `packages/kotlin/src/main/resources/${file}`]) {
      await mkdir(dirname(resolve(root, target)), { recursive: true });
      await copyFile(resolve(here, "../dist", file), resolve(root, target));
      console.log(resolve(root, target));
    }
  }
}
