import { readFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseSignature } from "../src/signature.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const catalog = JSON.parse(await readFile(resolve(here, "../src/editors.json"), "utf8"));

const HEADER = "// Generated by packages/native/scripts/generate-editors.mjs from src/editors.json. Do not edit: change the catalog and run `pnpm native`.\n";

/** Types the hand-written code has, which the catalog may name. */
const SHARED = Object.fromEntries((catalog.shared ?? []).map((n) => [n, `Pli${n}`]));

const optional = (t) => t.endsWith("?");
const base = (t) => t.replace(/\?$/, "");
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const SWIFT_PRIMITIVE = { string: "String", int: "Int", double: "Double", bool: "Bool", json: "PliJSON", scalar: "PliJSON" };
const KOTLIN_PRIMITIVE = { string: "String", int: "Int", double: "Double", bool: "Boolean", json: "JsonElement", scalar: "JsonElement" };
const KOTLIN_INPUT = { json: "Any?", scalar: "Any?" };

/** The Swift or Kotlin spelling of a catalog type. `input` is for a parameter, where JSON is whatever the caller has. */
function typeName(type, lang, input = false) {
  const q = optional(type);
  const t = base(type);
  let name;
  if (t.startsWith("[")) name = lang === "swift" ? `[${typeName(t.slice(1, -1), lang, input)}]` : `List<${typeName(t.slice(1, -1), lang, input)}>`;
  else if (t.startsWith("map<")) name = lang === "swift" ? `[String: ${typeName(t.slice(4, -1), lang, input)}]` : `Map<String, ${typeName(t.slice(4, -1), lang, input)}>`;
  else if (lang === "swift" && SWIFT_PRIMITIVE[t]) name = SWIFT_PRIMITIVE[t];
  else if (lang === "kotlin" && input && KOTLIN_INPUT[t]) return KOTLIN_INPUT[t];
  else if (lang === "kotlin" && KOTLIN_PRIMITIVE[t]) name = KOTLIN_PRIMITIVE[t];
  else name = SHARED[t] ?? `Pli${t}`;
  return q ? `${name}?` : name;
}

const swiftReturn = (r) => (r === "void" ? "Void" : typeName(r, "swift"));
const kotlinReturn = (r) => (r === "void" ? "Unit" : typeName(r, "kotlin"));
const kebabToCamel = (v) => v.replace(/-(\w)/g, (_, c) => c.toUpperCase());

function docLines(text, indent) {
  return `${indent}/// ${text.replace(/\n/g, `\n${indent}/// `)}\n`;
}
const kdoc = (text, indent) => `${indent}/** ${text.replace(/\*\//g, "*&#47;")} */\n`;

/** A file method's parameters, written like a method signature. */
function fileParams(entry, enums) {
  if (!entry.params) return [];
  return parseSignature(`f(${entry.params}): void`, enums).params;
}

function swiftEditor(name, editor) {
  const enums = editor.enums ?? {};
  let out = HEADER + "import Foundation\n\n";
  for (const [en, values] of Object.entries(enums)) {
    out += `/// The choices for ${en}.\npublic enum Pli${en}: String, Codable, CaseIterable, Sendable, PliArg {\n`;
    for (const v of values) out += kebabToCamel(v) === v ? `    case ${v}\n` : `    case ${kebabToCamel(v)} = "${v}"\n`;
    out += "}\n\n";
  }
  for (const [tn, spec] of Object.entries(editor.types ?? {})) {
    const hasId = "id" in spec.fields;
    out += docLines(spec.doc, "");
    out += `public struct Pli${tn}: Codable, Equatable, Sendable${hasId ? ", Identifiable" : ""} {\n`;
    for (const [fn, ft] of Object.entries(spec.fields)) out += `    public let ${fn}: ${typeName(ft, "swift")}\n`;
    out += "}\n\n";
  }
  out += `extension ${editor.class} {\n`;
  for (const m of editor.methods) {
    const sig = parseSignature(m.sig, enums);
    const single = sig.params.length === 1;
    const params = sig.params.map((p) => `${single ? "_ " : ""}${p.name}: ${typeName(p.type, "swift", true)}${optional(p.type) ? " = nil" : ""}`).join(", ");
    const args = `[${sig.params.map((p) => `${p.name}.pliJSON`).join(", ")}]`;
    out += docLines(m.doc, "    ");
    if (sig.returns === "void") out += `    public func ${sig.name}(${params}) throws {\n        try runVoid("${sig.name}", ${args})\n    }\n\n`;
    else out += `    @discardableResult\n    public func ${sig.name}(${params}) throws -> ${swiftReturn(sig.returns)} {\n        try run("${sig.name}", ${args})\n    }\n\n`;
  }
  for (const f of editor.files ?? []) {
    const params = fileParams(f, enums);
    const list = params.map((p) => `${p.name}: ${typeName(p.type, "swift", true)}${optional(p.type) ? " = nil" : ""}`);
    const options = params.length
      ? `        var options: [String: PliJSON] = [:]\n${params.map((p) => (optional(p.type) ? `        if let ${p.name} { options["${p.name}"] = ${p.name}.pliJSON }\n` : `        options["${p.name}"] = ${p.name}.pliJSON\n`)).join("")}`
      : "";
    const pass = params.length ? ", options: options" : "";
    out += docLines(f.doc, "    ");
    if (f.direction === "export") {
      const call = f.async ? `try await exportFileAsync("${f.format}"${pass})` : `try exportFile("${f.format}"${pass})`;
      const ret = f.text ? "String" : "Data";
      const body = f.text ? `String(decoding: ${call}, as: UTF8.self)` : call;
      out += `    public func ${f.name}(${list.join(", ")}) ${f.async ? "async " : ""}throws -> ${ret} {\n${options}        return ${body}\n    }\n\n`;
    } else {
      const input = f.text ? "_ text: String" : "_ data: Data";
      out += `    @discardableResult\n    public func ${f.name}(${[input, ...list].join(", ")}) throws -> PliFileImport {\n${options}        return try importFile("${f.format}", ${f.text ? "text: text" : "data: data"}${pass})\n    }\n\n`;
    }
  }
  out += "}\n";
  return out;
}

const KOTLIN_IMPORTS = `import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonElement
`;

function kotlinEditor(name, editor) {
  const enums = editor.enums ?? {};
  let out = HEADER + `package dev.pli\n\n${KOTLIN_IMPORTS}\n`;
  for (const [en, values] of Object.entries(enums)) {
    out += `/** The choices for ${en}. */\nenum class Pli${en}(override val wire: String) : PliWire {\n${values.map((v, i) => `    ${v.toUpperCase().replace(/-/g, "_")}("${v}")${i === values.length - 1 ? ";" : ","}`).join("\n")}\n}\n\n`;
  }
  for (const [tn, spec] of Object.entries(editor.types ?? {})) {
    out += kdoc(spec.doc, "");
    out += `@Serializable\ndata class Pli${tn}(\n`;
    for (const [fn, ft] of Object.entries(spec.fields)) out += `    val ${fn}: ${typeName(ft, "kotlin")}${optional(ft) ? " = null" : ""},\n`;
    out += ")\n\n";
  }
  for (const m of editor.methods) {
    const sig = parseSignature(m.sig, enums);
    const params = sig.params.map((p) => `${p.name}: ${typeName(p.type, "kotlin", true)}${optional(p.type) ? " = null" : ""}`).join(", ");
    const args = sig.params.map((p) => p.name).join(", ");
    out += kdoc(m.doc, "");
    if (sig.returns === "void") out += `fun ${editor.class}.${sig.name}(${params}) = invokeUnit("${sig.name}"${args ? `, ${args}` : ""})\n\n`;
    else out += `fun ${editor.class}.${sig.name}(${params}): ${kotlinReturn(sig.returns)} = invokeAs("${sig.name}"${args ? `, ${args}` : ""})\n\n`;
  }
  for (const f of editor.files ?? []) {
    const params = fileParams(f, enums);
    const list = params.map((p) => `${p.name}: ${typeName(p.type, "kotlin", true)}${optional(p.type) ? " = null" : ""}`);
    const options = params.length ? `, mapOf(${params.map((p) => `"${p.name}" to ${p.name}`).join(", ")})` : "";
    out += kdoc(f.doc, "");
    if (f.direction === "export") {
      const call = `${f.async ? "exportFileAsync" : "exportFile"}("${f.format}"${options})`;
      out += `${f.async ? "suspend " : ""}fun ${editor.class}.${f.name}(${list.join(", ")}): ${f.text ? "String" : "ByteArray"} = ${f.text ? `${call}.toString(Charsets.UTF_8)` : call}\n\n`;
    } else {
      const input = f.text ? "text: String" : "data: ByteArray";
      out += `fun ${editor.class}.${f.name}(${[input, ...list].join(", ")}): PliFileImport = ${f.text ? "importFileText" : "importFile"}("${f.format}", ${f.text ? "text" : "data"}${options})\n\n`;
    }
  }
  return out.trimEnd() + "\n";
}

const FILES = {
  docs: ["Documents", "Documents"],
  sheets: ["Sheets", "Sheets"],
  decks: ["Decks", "Decks"],
  pdf: ["Pdf", "Pdf"],
};

/** Every generated file for the editors in `editors.json`: its path and what it should say. */
export const editorOutputs = {};
for (const [name, editor] of Object.entries(catalog.editors)) {
  const [swiftName, kotlinName] = FILES[name];
  editorOutputs[`swift-${name}`] = { path: resolve(root, `packages/swift/Sources/Pli/${swiftName}.generated.swift`), text: swiftEditor(name, editor) };
  editorOutputs[`kotlin-${name}`] = { path: resolve(root, `packages/kotlin/src/main/kotlin/dev/pli/${kotlinName}.generated.kt`), text: kotlinEditor(name, editor) };
}

