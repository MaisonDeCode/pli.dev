#!/usr/bin/env node
/**
 * Regenerates `packages/core/src/fonts/google-data.ts`, the font catalogue Pli ships.
 *
 * Reads two public, key-less JSON documents:
 *   - https://api.fontsource.org/v1/fonts            families, categories, weights, styles, subsets and licences
 *   - https://fonts.google.com/metadata/fonts        Google's popularity ranking (orders the catalogue), and the
 *                                                    unicode ranges of the common scripts are taken from Fontsource's detail pages.
 *
 * Usage:  node scripts/generate-font-catalogue.mjs [--offline <dir>]   (--offline reads fsrc.json/gmeta.json from <dir>; the unicode ranges are still fetched)
 *
 * The output is a snapshot: it never changes at run time, so editors work offline and hosts see no surprise new fonts.
 * Run it again (and commit the file) when you want newer families.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../packages/core/src/fonts/google-data.ts");
const offline = process.argv.includes("--offline") ? process.argv[process.argv.indexOf("--offline") + 1] : undefined;

const getJson = async (url, file) => (offline ? JSON.parse(readFileSync(join(offline, file), "utf8")) : (await fetch(url)).json());
const fsrc = await getJson("https://api.fontsource.org/v1/fonts", "fsrc.json");
const gmeta = await getJson("https://fonts.google.com/metadata/fonts", "gmeta.json");

const FREE = new Set(["OFL-1.1", "Apache-2.0", "CC0-1.0", "mit", "MIT", "Unlicense", "UFL-1.0"]);
const NOT_TEXT = new Set(["math", "symbols", "symbols2", "music", "emoji", "braille"]);
const CATEGORY = { "sans-serif": "s", serif: "r", display: "d", monospace: "m", handwriting: "h", other: "d" };

const rank = new Map(gmeta.familyMetadataList.map((f) => [f.family, f.popularity]));
const families = fsrc
  .filter((f) => (f.type === "google" || f.type === "other") && f.category in CATEGORY && FREE.has(f.license))
  .filter((f) => f.subsets.some((s) => !NOT_TEXT.has(s)))
  .sort((a, b) => (rank.get(a.family) ?? 1e6) - (rank.get(b.family) ?? 1e6) || a.family.localeCompare(b.family));

const subsets = [];
const subsetIndex = (s) => {
  let i = subsets.indexOf(s);
  if (i < 0) i = subsets.push(s) - 1;
  return i;
};
const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const lines = families.map((f) => {
  const weights = f.weights.map((w) => Math.round(w / 100)).filter((d) => d >= 1 && d <= 9);
  const flags = f.styles.includes("italic") ? "i" : "";
  const list = f.subsets.filter((s) => !NOT_TEXT.has(s)).map(subsetIndex).join(",");
  const cols = [f.family, CATEGORY[f.category], [...new Set(weights)].sort().join(""), flags, list];
  if (slug(f.family) !== f.id) cols.push(f.id);
  return cols.join(";");
});

// Unicode ranges for the scripts that are one slice each: taken from the first family that has the subset.
const WANT = ["latin", "latin-ext", "cyrillic", "cyrillic-ext", "greek", "greek-ext", "vietnamese", "hebrew", "arabic", "thai", "devanagari", "bengali", "tamil", "telugu", "kannada", "gujarati", "gurmukhi", "malayalam", "khmer", "armenian", "georgian"];
const ranges = {};
for (const name of WANT) {
  const owner = families.find((f) => f.subsets.includes(name));
  if (!owner) continue;
  const detail = await (await fetch(`https://api.fontsource.org/v1/fonts/${owner.id}`)).json();
  const range = detail?.unicodeRange?.[name];
  if (range) ranges[name] = range;
}

const body = `// Generated by scripts/generate-font-catalogue.mjs from the Fontsource and Google Fonts metadata. Do not edit by hand.
// ${families.length} families, most popular first. One line each: family;category;weights (hundreds);flags (i = has italics);subset numbers[;fontsource id].

/** Names of the subsets (scripts) the lines refer to by number. */
export const GOOGLE_SUBSETS = ${JSON.stringify(subsets.join("|"))};

/** Unicode ranges of the scripts that are one file each (the others are loaded whole). */
export const GOOGLE_RANGES: Record<string, string> = ${JSON.stringify(ranges, null, 1)};

/** The families, one per line. */
export const GOOGLE_DATA = ${JSON.stringify(lines.join("\n"))};
`;
writeFileSync(out, body);
console.log(`${families.length} families, ${subsets.length} subsets, ${Object.keys(ranges).length} ranges`);
